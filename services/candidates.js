const CANDIDATE_POOL_CAP = 60;

// ---------- "Date aware" picker: optional planning date/range ----------
// Toronto-local YYYY-MM-DD, inclusive. Left unset, DayHop plans for "any
// day" exactly as before (no date filtering, current weather applies).
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const MAX_DATE_WINDOW_DAYS = 90;

// Normalizes the picker's raw `date`/`date_end` strings into a validated
// window, or null when the user never engaged it. A past date clamps to
// today (DayHop only plans ahead), an end before start clamps to start, and
// a runaway range caps at 90 days so a stray far-future end can't blow out
// the event connectors' daysAhead fetch.
function parseDateWindow(date, dateEnd) {
  if (!date || !DATE_RE.test(date)) return null;
  const today = torontoToday();
  const start = date < today ? today : date;
  const capEnd = addDays(start, MAX_DATE_WINDOW_DAYS);
  let end = dateEnd && DATE_RE.test(dateEnd) && dateEnd > start ? dateEnd : start;
  if (end > capEnd) end = capEnd;
  return { start, end };
}

function daysBetween(startStr, endStr) {
  const toUtc = s => { const [y, m, d] = s.split('-').map(Number); return Date.UTC(y, m - 1, d, 12); };
  return Math.round((toUtc(endStr) - toUtc(startStr)) / 86400000);
}

// ---------- Description cleanup: vendor boilerplate never reaches a card ----------
// Partner feeds ship descriptions full of purchase mechanics ("**PLEASE
// NOTE** tickets are subject to a delivery delay…"), refund policies, and
// markdown artifacts. None of that is a reason to visit a place, and raw
// asterisks next to DayHop's hand-written copy read as broken. Sentences
// about logistics are dropped; whatever remains is what describes the day.
const BOILERPLATE_RE = /\b(please note|important note|disclaimer|terms (and|&) conditions|refund|non.?refundable|all sales (are )?final|ticket delivery|delivery delay|prevent fraud|processing fee|convenience fee|service charge|box office|will.?call|id required|must be \d+|age restriction|no re.?entry|subject to (change|availability)|check.?in (opens|closes|required)|confirmation (email|number)|voucher|redeem)\b/i;

function cleanDescription(text) {
  if (!text || typeof text !== 'string') return text;
  let s = text
    .replace(/\*\*|__|\*|~~|#+\s/g, ' ')      // markdown emphasis/heading artifacts
    .replace(/<[^>]+>/g, ' ')                  // stray HTML
    .replace(/\s+/g, ' ')
    .trim();
  // Sentence-level pass: keep what sells the experience, drop the fine print.
  const sentences = s.split(/(?<=[.!?])\s+/);
  const kept = sentences.filter(sn => !BOILERPLATE_RE.test(sn));
  s = (kept.length ? kept : sentences).join(' ').trim();
  return s;
}

// ---------- Quality gate: only "10/10" candidates survive ----------
// Applied to the ranked pool in every mode, so the browse feed, prompt
// results, and re-plan swap-ins all draw from excellent material only.
// A candidate passes on the strongest evidence available for its kind:
//  - Rated venues/activities: rating >= 4.4 with a real review sample.
//  - Hand-curated entries: 10/10 by definition — a human picked them.
//  - Unrated events/civic listings: must be a complete, actionable listing
//    (description plus a venue, booking link, map link, or photo).
const QUALITY_MIN_RATING = 4.4;
const QUALITY_MIN_REVIEWS = 25;
// Strictness must never starve the feed in a sparse area: below this many
// survivors, top back up with the best-scored of the rest.
const QUALITY_FLOOR = 12;

function isTopQuality(c) {
  if (c.rating != null) {
    if (c.rating < QUALITY_MIN_RATING) return false;
    if ((c.rating_count ?? QUALITY_MIN_REVIEWS) < QUALITY_MIN_REVIEWS) return false;
    return true;
  }
  if (c.source === 'curated' || c.source === 'curated_catalog') return true;
  if (c.wow === true) return true;
  return Boolean(c.description && (c.venue || c.booking_url || c.maps_url || c.image_url));
}

// Operates on scoreCandidates output so the floor top-up picks the most
// RELEVANT of the rejects, not arbitrary ones.
function qualityGate(scored) {
  const strict = scored.filter(e => isTopQuality(e.candidate));
  if (strict.length >= QUALITY_FLOOR) return strict;
  const rest = scored
    .filter(e => !isTopQuality(e.candidate))
    .sort((a, b) => b.score - a.score)
    .slice(0, QUALITY_FLOOR - strict.length);
  return [...strict, ...rest];
}

// opts (all optional, used by the surprise feed's "Next" pages):
//   radiusKm      — override the Places search radius (wider-net sweeps)
//   excludeIds    — Set of candidate ids already shown to this user
//   excludeTitles — Set of normTitle'd titles already shown (catches the
//                   same venue arriving under a different source's id)
async function gatherCandidates(prompt, locationText, eventKeyword, filter, userCoords, mode, dateWindow = null, opts = {}) {
  let geo = null;
  let weather = null;
  // With shared coordinates the locality comes from reverse geocoding and
  // drives the GTA gate, Viator destination, and Grok's location context.
  let resolvedCity = null;

  if (userCoords) {
    geo = { lat: userCoords.lat, lng: userCoords.lng };
    try {
      resolvedCity = (await maps.reverseGeocode(userCoords)).city;
    } catch (err) {
      console.warn('[candidates] Reverse geocode unavailable:', err.message);
    }
  } else {
    // Normalize GTA-picker values into something geocodable: "Across the GTA"
    // grounds on Toronto; strip "(Downtown)"-style hints; bias bare GTA town
    // names to Ontario so we don't geocode a same-named city elsewhere.
    const geoText = toGeocodable(locationText);
    try {
      geo = await maps.geocode(geoText);
    } catch (err) {
      console.warn('[candidates] Geocoding unavailable:', err.message);
    }
  }

  const localityText = resolvedCity || locationText;

  // Current conditions only mean something for a day that includes "now" —
  // applying today's weather bias to a future date would be a quiet lie, so
  // skip the call (and any weather-driven indoor/outdoor steering) entirely
  // when the requested window doesn't cover today.
  const today = torontoToday();
  const weatherApplies = !dateWindow || (dateWindow.start <= today && today <= dateWindow.end);
  // Weather and the advisory area sources (air quality, ECCC alerts) are
  // independent network calls — start weather now and hand the in-flight
  // promise to getAdvisories, which resolves all three in one parallel
  // batch. They used to run strictly one after the other.
  const weatherPromise = (geo && weatherApplies)
    ? weatherSvc.getConditions({ lat: geo.lat, lng: geo.lng }).catch(err => {
        console.warn('[candidates] Weather unavailable:', err.message);
        return null;
      })
    : Promise.resolve(null);

  // Advisories ("should I even go today?"): air quality + condition-derived
  // warnings for the target area. Resolved BEFORE the source batch — cheap
  // (one cached air-quality call; the rest derives from the weather we
  // already hold) and worth it, because a shelter-level advisory changes
  // WHAT we search for, not just how results rank.
  let advisoryResult = { advisories: [], status: 'unavailable' };
  if (geo) {
    try {
      advisoryResult = await advisoriesSvc.getAdvisories({ lat: geo.lat, lng: geo.lng, conditions: weatherPromise });
    } catch (err) {
      console.warn('[candidates] advisories unavailable:', err.message);
    }
  }
  weather = await weatherPromise;
  const advisoryPressure = advisoriesSvc.advisoryEffects(advisoryResult.advisories);

  // The GTA-only sources (open data, curated, org-scoped Eventbrite) would be
  // wrong grounding for a request about some other city — skip them there.
  // A typed postal code ("L4C 1J8") won't name a town, so also check the
  // geocoder's formatted address.
  const isGta = GTA_TOWNS.test(String(localityText || '')) ||
    Boolean(geo && GTA_TOWNS.test(String(geo.formatted_address || '')));

  // Seasonal spotlight: World Cup while it's live, then the next Ontario
  // stat/bank holiday. Widens the event fetch window to cover the long
  // weekend and boosts events landing on it (relevance.js).
  const spotlight = getSpotlight();

  // How far ahead the event connectors should fetch: at least far enough to
  // cover the spotlight window, and — when the "date aware" picker is set to
  // something beyond that — at least far enough to reach the requested date.
  const daysAhead = dateWindow
    ? Math.max(eventDaysAhead(spotlight), daysBetween(today, dateWindow.end) + 2)
    : eventDaysAhead(spotlight);

  // Theme expansion: "swimming" fans out to pools, beaches, splash pads,
  // paddling rentals, waterparks — the neighbourhood of the request, not
  // just its literal words.
  const themes = matchThemes(prompt);
  const themeQueries = themes.flatMap(t => t.placesQueries).slice(0, 4);

  // Under a warning+ "stay out of the open air" advisory (smoke, dangerous
  // heat/wind), a nature-first prompt would fill the pool with exactly the
  // places users shouldn't visit today. One extra indoor-refuge search
  // guarantees the ranked pool contains genuine alternatives to offer.
  // Unshifted, not pushed: the google_places source cap trims from the end,
  // and refuge results must survive it.
  if (advisoryPressure.avoid_outdoor >= 2) {
    themeQueries.unshift('best indoor attractions museums galleries aquariums');
  }

  // Dining is universal: one always-on query keeps the "New & notable
  // dining" shelf fed in BOTH modes (the Adventure prompts contain no food
  // vocabulary at all, so without this the shelf starves there). Cached 6h
  // per grid like every other text search.
  if (!themeQueries.some(q => /restaurant|food|dessert|brunch|patio|cafe/i.test(q))) {
    themeQueries.push('highly rated restaurants and cafes');
  }

  // One parallel batch: each source is independently optional — a failed or
  // unconfigured source logs one warning and contributes nothing.
  const sources = [
    {
      name: 'google_places',
      run: () => geo ? searchPlacesWithThemes(prompt, themeQueries, geo, Boolean(userCoords), opts.radiusKm ? opts.radiusKm * 1000 : null) : []
    },
    {
      // Fetch a deep top-20 and surface a daily-rotating window of 6 — the
      // old top-8-by-rating fetch meant the SAME products led every feed in
      // every GTA town, every day (the whole region maps to one Viator
      // destination, "Toronto").
      name: 'viator',
      run: () => viator.resolveDestinationId(toViatorDestination(localityText))
        .then(destinationId => viator.searchActivities({ destinationId, topX: 40 }))
        // Pre-filter to products that can actually reach the feed, BEFORE
        // the daily rotation — otherwise the 6-slot window fills with
        // products the downstream gates will kill and Viator contributes
        // nothing (which is exactly what happened for months):
        //  - airport transfers/tour-operator listings die at the
        //    service-business filter;
        //  - Viator sorts by rating, and Toronto's 5.0-rated tours are
        //    long-tail (13-24 reviews) — below the 25-review quality
        //    gate. Filter to gate-passing products; fetch deeper (40) so
        //    rotation still has variety.
        .then(activities => activities.filter(a =>
          !/transfer|airport|shuttle|taxi|limo|chauffeur/i.test(a.title || '') &&
          (a.rating ?? 0) >= QUALITY_MIN_RATING &&
          (a.rating_count ?? 0) >= QUALITY_MIN_REVIEWS))
        .then(activities => rotateDaily(activities, 6)
          .map(a => Object.assign({}, a, { id: a.product_code })))
    },
    {
      name: 'getyourguide',
      run: () => geo
        ? gyg.searchActivities({ lat: geo.lat, lng: geo.lng, query: prompt })
            .then(activities => activities.map(a => Object.assign({}, a, { id: a.activity_id })))
        : []
    },
    {
      name: 'ticketmaster',
      run: () => geo
        ? ticketmaster.searchEvents({
            lat: geo.lat, lng: geo.lng, keyword: eventKeyword || undefined,
            limit: SOURCE_CAPS.ticketmaster, daysAhead
          })
        : []
    },
    {
      name: 'eventbrite',
      run: () => isGta ? eventbrite.searchEvents({ limit: SOURCE_CAPS.eventbrite }) : []
    },
    {
      // Hyperlocal community events — works wherever Seeker has coverage,
      // so gated on geo, not the GTA.
      name: 'seeker',
      run: () => geo
        ? seeker.searchEvents({
            lat: geo.lat, lng: geo.lng, city: localityText,
            limit: SOURCE_CAPS.seeker, daysAhead
          })
        : []
    },
    {
      name: 'attractions_ontario',
      run: () => isGta ? attractionsOntario.searchEvents({ limit: SOURCE_CAPS.attractions_ontario }) : []
    },
    {
      name: 'civic_calendars',
      run: () => isGta ? civicCalendars.searchEvents({ limit: SOURCE_CAPS.civic_calendars }) : []
    },
    {
      name: 'toronto_open_data',
      run: () => isGta ? torontoOpenData.getUpcomingEvents({ limit: SOURCE_CAPS.toronto_open_data, keyword: eventKeyword || undefined }) : []
    },
    {
      name: 'york_open_data',
      run: () => isGta ? yorkOpenData.getCivicPlaces({ limit: SOURCE_CAPS.york_open_data, keyword: eventKeyword || undefined }) : []
    },
    {
      // Free library programming across every Toronto branch — kids clubs,
      // workshops, talks. GTA-gated (it's one library system).
      name: 'tpl_events',
      run: () => isGta ? tplEvents.getUpcomingEvents({ limit: SOURCE_CAPS.tpl_events }) : []
    },
    {
      // OSM lookouts/waterfalls/beaches/reserves — works anywhere there are
      // coordinates, so gated on geo, not the GTA.
      name: 'osm_nature',
      run: () => geo ? osmNature.getNatureSpots({ lat: geo.lat, lng: geo.lng, limit: SOURCE_CAPS.osm_nature }) : []
    },
    {
      name: 'curated',
      run: () => isGta ? upcomingCuratedEvents(SOURCE_CAPS.curated) : []
    },
    {
      // Region-aware: GTA browsers get the whole catalog; elsewhere in
      // Ontario, only entries anchored to the asked place (so an approved
      // Ottawa opening reaches Ottawa users, and never pollutes Kingston).
      name: 'curated_catalog',
      run: () => catalogCandidates(prompt, themes, SOURCE_CAPS.curated_catalog, {
        isGta,
        localityText: String(localityText || (geo && geo.formatted_address) || '')
      })
    }
  ];

  // Wall-clock guard: allSettled resolves when the SLOWEST source does, so
  // a single hung API (a busy Overpass, an Akamai tarpit) used to hold every
  // browse and plan hostage. 9s is generous for a well-behaved source;
  // anything slower is cut from THIS request and, thanks to each service's
  // own cache, usually contributes to the next one instead.
  const SOURCE_DEADLINE_MS = 9000;
  const withDeadline = (promise) => {
    promise.catch(() => {}); // a post-deadline failure must not be an unhandled rejection
    return Promise.race([
      promise,
      new Promise((resolve, reject) =>
        setTimeout(() => reject(new Error(`source deadline (${SOURCE_DEADLINE_MS}ms) exceeded`)), SOURCE_DEADLINE_MS).unref?.())
    ]);
  };
  const settled = await Promise.allSettled(sources.map(s => withDeadline(Promise.resolve().then(s.run))));
  const bySource = [];
  settled.forEach((result, i) => {
    if (result.status === 'fulfilled') {
      const cap = SOURCE_CAPS[sources[i].name] || 10;
      // Shallow-clone at the pool boundary: most sources serve object refs
      // straight out of long-lived caches, and the pipeline stamps
      // per-request fields (description cleanup, distance_km, engagement,
      // dedup backfill) — without the clone, one user's distances leak
      // into every later request that hits the same cache.
      const items = (result.value || []).slice(0, cap).map(c => ({ ...c }));
      if (items.length) bySource.push(items);
    } else {
      console.warn(`[candidates] ${sources[i].name} unavailable:`, result.reason && result.reason.message);
    }
  });

  // Dedup first (interleave order only decides which duplicate wins), then
  // rank the whole pool against the prompt so the cap trims the least
  // relevant candidates instead of whichever source came last.
  // Closed places are dropped before any of that — DayHop never recommends
  // (or spends a pool slot on) a place Google lists as closed.
  let pool = dedupCandidates(interleave(bySource))
    .filter(c => {
      const closed = advisoriesSvc.closureAdvisory(c.business_status, { place_id: c.id, title: c.title });
      if (closed) console.log(`[candidates] dropping closed place: ${c.title} (${c.business_status})`);
      return !closed;
    });

  // "Next" pages: everything already on the user's screen is excluded
  // BEFORE scoring, so the pool cap fills entirely with fresh material.
  // Titles are matched normalized — the same venue often returns under a
  // different id from a different source on the wider sweep.
  if (opts.excludeIds || opts.excludeTitles) {
    pool = pool.filter(c =>
      !(opts.excludeIds && opts.excludeIds.has(String(c.id))) &&
      !(opts.excludeTitles && opts.excludeTitles.has(normTitle(c.title))));
  }

  for (const c of pool) c.description = cleanDescription(c.description);

  // A dated event in the past is never a valid recommendation, whatever the
  // picker says — one stale card poisons trust in the whole feed.
  pool = pool.filter(c => {
    const past = c.date && DATE_RE.test(c.date) && c.date < today;
    if (past) console.log(`[candidates] dropping past event: ${c.title} (${c.date})`);
    return !past;
  });

  // "Date aware" picker: dated events outside the requested window are
  // dropped; evergreen candidates (no fixed date — most venues/activities)
  // are unaffected, since they're a fine idea on any day in the window.
  if (dateWindow) {
    pool = pool.filter(c => !c.date || (c.date >= dateWindow.start && c.date <= dateWindow.end));
  }

  // Distance is a first-class signal whenever we know where the day starts:
  // the user's shared coordinates, or failing that the picked city's
  // centroid. Without the centroid fallback a city pick had NO proximity
  // scoring at all — a gem around the corner in Scarborough ranked no
  // higher than a place 19 km across the region, and the wider search
  // radius made that hole very visible.
  const origin = userCoords || (geo ? { lat: geo.lat, lng: geo.lng } : null);
  if (origin) {
    for (const c of pool) {
      if (c.lat != null && c.lng != null) {
        c.distance_km = relevance.haversineKm(origin, { lat: c.lat, lng: c.lng });
      }
    }
    // Google text search treats its radius as a bias, not a boundary — a
    // famous "zipline park" 500 km away can outrank the local one. Places
    // results past 120 km are bias leaks, not day-trip options; curated
    // entries (e.g. Arrowhead's ice trail) stay — a human vouched for the
    // drive being worth it.
    pool = pool.filter(c => !(c.source === 'google_places' && c.distance_km != null && c.distance_km > 120));
  }

  // Discovery Phase 3 feedback loop: newly-opened items carry their last-30d
  // engagement (shortlist adds + outbound clicks) into scoring, so the
  // freshness lift grows for openings users actually embrace. Cheap: only
  // the handful of newly_opened ids are looked up, and the counts cache.
  const freshIds = pool.filter(c => c.newly_opened).map(c => c.id);
  if (freshIds.length) {
    try {
      const engagement = await analytics.engagementByIdea(freshIds);
      for (const c of pool) {
        if (c.newly_opened) c.engagement_30d = engagement[c.id] || 0;
      }
    } catch (err) { /* scoring proceeds with the base lift */ }
  }

  // Quality gate BEFORE the cap, so the pool fills with excellent
  // candidates instead of capping first and filtering what's left.
  const gated = qualityGate(relevance.scoreCandidates(pool, {
    prompt, themes, filter, mode, advisoryPressure, spotlight, dateWindow
  }));
  const candidates = relevance.selectTop(gated, CANDIDATE_POOL_CAP);

  // Wildcards: up to 3 daily-rotating picks from quality-gated material that
  // MISSED the cap — the deliberate "stumble on something" slots. Kept close
  // (≤60 km when distance is known) so a wildcard is a plausible day, not a
  // road trip. Marked so the feed can shelve them distinctly.
  const inPool = new Set(candidates.map(c => c.id));
  const rejects = gated
    .map(e => e.candidate)
    .filter(c => !inPool.has(c.id) && (c.distance_km == null || c.distance_km <= 60));
  for (const w of rotateDaily(rejects, 3)) {
    candidates.push(Object.assign({}, w, { wildcard: true }));
  }
  return {
    candidates,
    weather,
    usedGrounding: candidates.length > 0,
    resolvedCity,
    advisories: advisoryResult.advisories,
    advisoriesStatus: advisoryResult.status,
    spotlight,
    dateWindow: dateWindow || null,
    geo: geo ? { lat: geo.lat, lng: geo.lng } : null
  };
}

// Shared normalization for title-based exclusion (same shape as dedupKey's).
function normTitle(s) {
  return String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

// Coordinates from the browser (already rounded client-side). Anything
// malformed is silently ignored — the request proceeds city-based.
function sanitizeCoords(coords) {
  if (!coords || typeof coords !== 'object') return null;
  const lat = Number(coords.lat);
  const lng = Number(coords.lng);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;
  if (Math.abs(lat) > 90 || Math.abs(lng) > 180) return null;
  return { lat, lng };
}

// Raw-prompt Places search plus up to 4 theme-expanded searches, all in
// parallel; results from theme queries are tagged so the relevance scorer
// knows they were already intent-matched. When the user shared their real
// coordinates, bias tight (5 km — "around the corner") and add one wide
// raw-prompt search so standout options further out still appear.
// City picks get a 20 km radius: a GTA borough centroid + 15 km cut off
// its neighbours (North York couldn't see east Scarborough), and the
// deeper maxResults cost nothing extra — same request, bigger page.
// Google text search happily answers "cool down in the heat" with HVAC
// contractors — real businesses, terrible day-out ideas. Service trades and
// B2B categories are dropped at the source, unless the prompt itself names
// the trade (someone literally searching for a furnace repair gets it).
const SERVICE_TYPES = new Set([
  'general_contractor', 'electrician', 'plumber', 'roofing_contractor',
  'painter', 'moving_company', 'storage', 'locksmith', 'laundry',
  'insurance_agency', 'real_estate_agency', 'real_estate_agent', 'lawyer',
  'accounting', 'finance', 'atm', 'bank', 'car_dealer', 'car_rental',
  'car_repair', 'car_wash', 'gas_station', 'dentist', 'doctor', 'dental_clinic',
  'drugstore', 'hospital', 'physiotherapist', 'veterinary_care',
  'funeral_home', 'travel_agency', 'insurance_company', 'corporate_office',
  'telecommunications_service_provider',
  // NB: 'manufacturer' and 'consultant' deliberately absent — Google noise-
  // tags food shops with both (an ice cream shop typed 'consultant' in the
  // wild), and every real trade hit carries a stronger type anyway.
  'wholesaler', 'home_improvement_store'
]);
const SERVICE_NAME_RE = /\b(hvac|heating|cooling|furnace|air condition\w*|duct(?:s|less|work)?|plumb\w*|roofing|renovation\w*|insulation|contractor\w*|gas (?:service|fitting)s?|water heater\w*|appliance (?:repair|service)s?|windows? (?:and|&) doors|mortgage\w*|realt\w*)\b|\bheat\W{0,3}(?:and|&|\/|\+|n)?\W{0,3}cool/i;

function isServiceBusiness(place) {
  if ((place.types || []).some(t => SERVICE_TYPES.has(t))) return true;
  return SERVICE_NAME_RE.test(place.title || '');
}

// Zero reviews AND no categorization beyond "a place exists here" — nothing
// for a recommendation to stand on ("Lidoma Airplus Inc." was an HVAC shop
// wearing exactly this non-profile). Any real venue clears one of the two.
const GENERIC_TYPES = new Set(['point_of_interest', 'establishment', 'service', 'store']);
function isUnverifiableStorefront(place) {
  return (place.rating_count || 0) === 0 &&
    (place.types || []).every(t => GENERIC_TYPES.has(t));
}

async function searchPlacesWithThemes(prompt, themeQueries, geo, hyperLocal = false, radiusOverride = null) {
  const radiusMeters = radiusOverride || (hyperLocal ? 5000 : 20000);
  const searches = [
    maps.searchPlaces({ query: prompt, lat: geo.lat, lng: geo.lng, radiusMeters, maxResults: 16 })
      .then(places => places.map(p => Object.assign({}, p, { source: 'google_places', id: p.place_id })))
  ];
  if (hyperLocal && !(radiusOverride >= 20000)) {
    searches.push(
      maps.searchPlaces({ query: prompt, lat: geo.lat, lng: geo.lng, radiusMeters: 20000, maxResults: 10 })
        .then(places => places.map(p => Object.assign({}, p, { source: 'google_places', id: p.place_id })))
        .catch(() => [])
    );
  }
  for (const query of themeQueries) {
    searches.push(
      maps.searchPlaces({ query, lat: geo.lat, lng: geo.lng, radiusMeters, maxResults: 10 })
        .then(places => places.map(p => Object.assign({}, p, { source: 'google_places', id: p.place_id, theme_hit: true })))
        .catch(err => {
          console.warn(`[candidates] places theme search "${query}" failed:`, err.message);
          return [];
        })
    );
  }
  const results = await Promise.all(searches);
  // The trade gate stands down only when the user explicitly asked for one.
  const wantsTrades = SERVICE_NAME_RE.test(prompt || '');
  const seen = new Set();
  const out = [];
  for (const place of results.flat()) {
    if (seen.has(place.place_id)) continue;
    seen.add(place.place_id);
    if (!wantsTrades && isServiceBusiness(place)) {
      console.log(`[candidates] dropping service business: ${place.title}`);
      continue;
    }
    if (isUnverifiableStorefront(place)) {
      console.log(`[candidates] dropping unverifiable storefront: ${place.title}`);
      continue;
    }
    out.push(place);
  }
  return out;
}

// Evergreen curated catalog entries, season-filtered and pre-ranked against
// the prompt so only the most fitting slice of the catalog joins the pool.
function catalogCandidates(prompt, themes, limit, regionOpts) {
  const month = Number(torontoToday().slice(5, 7));
  // Hand-curated entries plus the discovery autopilot's verified auto-adds
  // (services/autoCatalog) — same shape, same scoring, Canada-wide.
  // Coarse seasonal tags gate with shoulder months (data/seasons.js);
  // fine-grained seasonal ranking happens in relevance.js scoring.
  let eligible = [...curatedCatalog, ...autoCatalog.entries()]
    .filter(e => seasons.isCatalogSeasonEligible(e.seasonal, month));

  // Outside the GTA, only entries anchored to the asked place qualify —
  // matched by city token against the entry's location/venue/tags. No
  // token or no matches → the catalog simply contributes nothing there.
  if (regionOpts && regionOpts.isGta === false) {
    const token = String(regionOpts.localityText || '').toLowerCase().split(/[,(]/)[0].trim();
    eligible = token.length >= 3
      ? eligible.filter(e =>
          `${e.location || ''} ${e.venue || ''} ${(e.tags || []).join(' ')}`.toLowerCase().includes(token))
      : [];
  }

  // "Just opened" decay: an entry is new from opened_at until new_until.
  // Defaults: 120 days for hand-curated entries, 60 for autopilot adds
  // (whose opened_at is the publish date, not a verified opening date).
  // A year of "new" let one attraction lead every feed for twelve months.
  const todayYmd = torontoToday();
  const isNewlyOpened = e => Boolean(
    e.opened_at && e.opened_at <= todayYmd &&
    todayYmd <= (e.new_until || addDays(e.opened_at, e.auto === true ? 60 : 120)));

  const normalized = eligible.map(e => ({
    source: 'curated_catalog',
    id: e.id,
    title: e.title,
    description: e.description,
    category: e.category,
    tags: e.tags,
    date: null,
    venue: e.venue,
    address: e.location,
    location: e.location,
    lat: e.lat != null ? e.lat : (catalogCoords[e.id] ? catalogCoords[e.id].lat : null),
    lng: e.lng != null ? e.lng : (catalogCoords[e.id] ? catalogCoords[e.id].lng : null),
    good_for_ages: e.good_for_ages,
    cost_tier: e.cost_tier,
    price_from: null,
    currency: null,
    image_url: null,
    booking_url: e.booking_url || null,
    maps_url: e.maps_url,
    rating: null,
    wow: e.wow === true,
    newly_opened: isNewlyOpened(e),
    // Discovery-autopilot provenance (routes/surprise.js groups on these):
    // auto = published by the engine; buzz_score = social buzz at publish.
    auto: e.auto === true,
    buzz_score: e.buzz_score != null ? e.buzz_score : null
  }));

  const ranked = relevance.selectTop(
    relevance.scoreCandidates(normalized, { prompt, themes }),
    limit
  );
  // Newly-opened entries bypass the catalog quota — being surfaced while
  // new IS their job. But at most 3 per day, rotating through the eligible
  // set on a daily seed, so a busy opening season can't crowd the feed with
  // the same few names every single day.
  const rankedIds = new Set(ranked.map(r => r.id));
  const allFresh = normalized.filter(e => e.newly_opened && !rankedIds.has(e.id));
  const fresh = rotateDaily(allFresh, 3);
  const freshIds = new Set(fresh.map(e => e.id));
  return fresh.concat(ranked.filter(r => !freshIds.has(r.id)));
}

// Deterministic Toronto-calendar-day seed: feeds rotate day to day without
// per-request randomness (which would defeat the route-level caches).
function dailySeed() {
  const s = torontoToday();
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}

// Take `count` items from `list` starting at a day-seeded offset, wrapping —
// every item gets its turn across days, and today's pick is stable all day.
function rotateDaily(list, count) {
  if (list.length <= count) return list;
  const start = dailySeed() % list.length;
  const out = [];
  for (let i = 0; i < count; i++) out.push(list[(start + i) % list.length]);
  return out;
}

// Round-robin across the source lists so grok.js's 40-candidate cap trims
// every source proportionally instead of chopping off whichever came last.
function interleave(lists) {
  const out = [];
  const longest = Math.max(0, ...lists.map(l => l.length));
  for (let i = 0; i < longest; i++) {
    for (const list of lists) {
      if (i < list.length) out.push(list[i]);
    }
  }
  return out;
}

// The same real-world event often arrives from two sources (e.g. Ticketmaster
// and Eventbrite). Keep the first candidate seen for a title+venue (or
// title+date) key, fill its null fields from later duplicates, and record the
// extra source names so the frontend can badge "+1 source".
function dedupCandidates(candidates) {
  const FILLABLE = ['description', 'category', 'date', 'datetime', 'venue', 'address', 'lat', 'lng',
    'price_from', 'currency', 'cost_tier', 'image_url', 'booking_url', 'maps_url', 'website', 'rating'];
  const byKey = new Map();
  for (const c of candidates) {
    const key = dedupKey(c);
    const kept = byKey.get(key);
    if (!kept) { byKey.set(key, c); continue; }
    for (const f of FILLABLE) {
      if ((kept[f] == null || kept[f] === '') && c[f] != null && c[f] !== '') kept[f] = c[f];
    }
    if (c.source && c.source !== kept.source) {
      kept.also_from = kept.also_from || [];
      if (!kept.also_from.includes(c.source)) kept.also_from.push(c.source);
    }
  }
  return [...byKey.values()];
}

function dedupKey(c) {
  const norm = s => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
  const title = norm(c.title);
  const venue = norm(c.venue);
  return venue ? `${title}|v:${venue}` : `${title}|d:${c.date || ''}`;
}

